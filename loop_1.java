/*Write a program that prints "Hello Coddy: " and the i value from 3 to 27 
(including, which means printing the numbers 3, 4, 5, ..., 26, 27,
making it 27 - 3 + 1 = 25 times in total), do it using a for loop.*/

public class loop_1{
    public static void main(String[] args){
        for(int i=3;i<=27;i++){
            System.out.println("Hello Coddy: "+i);
        }
    }
}