/* declare a double variable name price and initialise its vale 99.99 
1. cost price variable to an int and stores result in intPrice
2. print value of Price and intPrice */

public class type_casting1 {
    public static void main(String[] args) {
        double price = 99.99;
        int intPrice =(int)price;
        System.out.println("Price: " + price);
        System.out.println("Int Price: " + intPrice);
    }
}
